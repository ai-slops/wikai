let root: string;
let vault: string;
let configPath: string;
let originalPath: string | undefined;

beforeEach(async () => {
  ({ root, vault, configPath } = await createServiceFixture());
  originalPath = process.env["PATH"];
  const bin = join(root, "bin");
  await mkdir(bin);
  await writeFile(
    join(bin, "docker"),
    `#!/bin/sh
if [ "$1" = "image" ] && [ "$2" = "inspect" ]; then
  printf 'sha256:%064d\\n' 1
  exit 0
fi
exit 1
`,
  );
  await chmod(join(bin, "docker"), 0o755);
  process.env["PATH"] = `${bin}:${originalPath ?? "/usr/bin:/bin"}`;
  await mkdir(join(vault, "public-components"));
  await writeFile(
    join(vault, "public-components", "Card.tsx"),
    "export const Card = () => 'new';\n",
  );
  await writeFile(configPath, `${await readFile(configPath, "utf8")}mdx:\n  enabled: true\n`);
  await writeFile(
    join(vault, "note.mdx"),
    `---
id: prv_note
title: Note
public:
  id: pub_note
  status: published
  mode: mirror
  kind: knowledge
  slug: /knowledge/note
  summary: Note summary
  contentState: stable
  knowledge:
    documentType: topic
---
import { Card } from './public-components/Card.tsx'

<Card />
`,
  );
});

afterEach(async () => {
  if (originalPath === undefined) delete process.env["PATH"];
  else process.env["PATH"] = originalPath;
  await rm(root, { recursive: true, force: true });
});

async function seedCurrentMdxCache(): Promise<void> {
  const config = await loadConfig(configPath);
  const snapshotFor = async (body: string, sourcePath: string): Promise<MdxSnapshot> => {
    const image = config.mdx?.image ?? "wikai-mdx:local";
    const imageId = await resolveMdxImage(image);
    const componentRoots = config.mdx?.componentRoots ?? ["public-components"];
    const dataRoots = config.mdx?.dataRoots ?? ["public-data"];
    const immutable = createMdxInput({
      body,
      sourcePath,
      snapshot: await snapshotPublicDependencies(config),
      image,
      imageId,
      componentRoots,
      dataRoots,
    });
    const artifact = Buffer.from("new generated bytes");
    return {
      schemaVersion: 1,
      contentInputHash: immutable.contentInputHash,
      profileDigest: immutable.profileDigest,
      runtime: { image, imageId },
      identity: { sourcePath: immutable.sourcePath, componentRoots, dataRoots },
      dependencies: [...immutable.files],
      artifact: {
        html: {
          path: "index.html",
          hash: hash(artifact),
          mime: "text/html; charset=utf-8",
          bytes: artifact.byteLength,
          data: artifact.toString("base64"),
        },
        scripts: [
          {
            path: "client.js",
            hash: hash(artifact),
            mime: "text/javascript; charset=utf-8",
            bytes: artifact.byteLength,
            data: artifact.toString("base64"),
          },
        ],
        styles: [],
      },
    };
  };
  const vaultSnapshot = await loadVault(config);
  const compiled = await compile(vaultSnapshot, config, [], async ({ body, sourcePath }) =>
    snapshotFor(body, sourcePath),
  );
  const current = compiled.publications[0];
  if (current?.mdx === undefined) throw new TypeError("Missing compiled MDX fixture");
  const cacheKey = hash(`${current.mdx.contentInputHash}\n${current.mdx.profileDigest}`);
  const cacheDirectory = join(config.publisher.stateDir, "mdx-cache");
  await mkdir(cacheDirectory, { recursive: true });
  await writeFile(
    join(cacheDirectory, `${cacheKey.slice("sha256:".length)}.json`),
    JSON.stringify(current.mdx),
  );
  const oldMdx = {
    ...current.mdx,
    profileDigest: hash("old shared component profile"),
    artifact: {
      ...current.mdx.artifact,
      scripts: current.mdx.artifact.scripts.map((script) => ({
        ...script,
        hash: hash("old generated bytes"),
        bytes: Buffer.byteLength("old generated bytes"),
        data: Buffer.from("old generated bytes").toString("base64"),
      })),
    },
  };
  const state = await PublisherState.open(config.publisher.stateDir);
  await state.approve(
    { ...current, exposureHash: hash("old exposure"), html: "old output", mdx: oldMdx },
    hash("old exposure"),
  );
}

it("plans and applies a profile-only update through the public service APIs", async () => {
  // Given an active MDX snapshot whose shared dependency profile is stale.
  await seedCurrentMdxCache();
  const publisher = await Publisher.open(configPath);
  const plan = await publisher.planComponentUpdateApproval();
  expect(
    plan.eligible.map((item) => item.publicId),
    JSON.stringify(plan),
  ).toEqual(["pub_note"]);

  // When the reviewed whole plan is applied.
  const result = await publisher.applyComponentUpdateApproval(plan.planHash);

  // Then the desired profile is active and the old immutable artifact remains readable.
  expect(result.approved).toHaveLength(1);
  const history = await (await PublisherState.open(publisher.config.publisher.stateDir)).history(
    "pub_note",
  );
  expect(history).toHaveLength(2);
  expect(Buffer.from(history[0]?.mdx?.artifact.scripts[0]?.data ?? "", "base64").toString()).toBe(
    "old generated bytes",
  );
});

it("rejects a reviewed service plan when public metadata changes before apply", async () => {
  // Given a reviewed component-only plan.
  await seedCurrentMdxCache();
  const publisher = await Publisher.open(configPath);
  const plan = await publisher.planComponentUpdateApproval();

  // When authored public metadata changes before apply.
  const sourcePath = join(vault, "note.mdx");
  await writeFile(
    sourcePath,
    (await readFile(sourcePath, "utf8")).replace("Note summary", "Changed summary"),
  );

  // Then the under-lock re-evaluation rejects the stale plan and preserves the active revision.
  await expect(publisher.applyComponentUpdateApproval(plan.planHash)).rejects.toMatchObject({
    code: "STALE_COMPONENT_PLAN",
  });
  const state = await PublisherState.open(publisher.config.publisher.stateDir);
  expect(await state.history("pub_note")).toHaveLength(1);
});
